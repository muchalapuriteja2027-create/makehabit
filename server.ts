import express, { Request, Response } from 'express';
import crypto from 'crypto';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());

// Helper: Razorpay Test Mode Credentials from environment
const getRazorpayCredentials = () => {
  const keyId = process.env.RAZORPAY_KEY_ID || process.env.VITE_RAZORPAY_KEY_ID;
  const keySecret = process.env.RAZORPAY_KEY_SECRET;
  return { keyId, keySecret };
};

/**
 * Health check & Razorpay configuration status
 * Never returns the secret key to clients.
 */
app.get('/api/razorpay/status', (_req: Request, res: Response) => {
  const { keyId, keySecret } = getRazorpayCredentials();
  res.json({
    paymentsLive: false,
    mode: 'test',
    planProposedPrice: '₹199 one-time',
    hasKeyId: Boolean(keyId),
    hasSecret: Boolean(keySecret),
    keyIdPreview: keyId ? `${keyId.substring(0, 8)}...` : null,
  });
});

/**
 * Razorpay Test Mode: Create Order endpoint
 * Securely creates a test order using server-side Razorpay credentials
 */
app.post('/api/razorpay/create-order', async (req: Request, res: Response) => {
  try {
    const { keyId, keySecret } = getRazorpayCredentials();

    if (!keyId || !keySecret) {
      res.status(503).json({
        success: false,
        isConfigured: false,
        error:
          'Razorpay Test Mode credentials are not yet configured on the server. Set VITE_RAZORPAY_KEY_ID and RAZORPAY_KEY_SECRET to test payments.',
      });
      return;
    }

    const { userId } = req.body;
    const amountInPaise = 19900; // ₹199.00 in paise
    const receiptId = `rcpt_${(userId || 'guest').substring(0, 10)}_${Date.now()}`;

    // Call Razorpay API with HTTP Basic Auth
    const authHeader = Buffer.from(`${keyId}:${keySecret}`).toString('base64');
    const razorpayResponse = await fetch('https://api.razorpay.com/v1/orders', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Basic ${authHeader}`,
      },
      body: JSON.stringify({
        amount: amountInPaise,
        currency: 'INR',
        receipt: receiptId,
        notes: {
          plan: 'premium_lifetime',
          userId: userId || 'anonymous',
        },
      }),
    });

    if (!razorpayResponse.ok) {
      const errorData = await razorpayResponse.json().catch(() => ({}));
      res.status(razorpayResponse.status).json({
        success: false,
        error: errorData.error?.description || 'Failed to create Razorpay test order.',
      });
      return;
    }

    const orderData = await razorpayResponse.json();

    res.json({
      success: true,
      isConfigured: true,
      orderId: orderData.id,
      amount: orderData.amount,
      currency: orderData.currency,
      keyId,
    });
  } catch (error: unknown) {
    const message = error instanceof Error ? error.message : 'Server error creating order';
    res.status(500).json({ success: false, error: message });
  }
});

/**
 * Razorpay Test Mode: Server-Side HMAC Payment Verification
 * Cryptographically verifies that the payment was generated by Razorpay
 * using HMAC SHA256 of order_id + "|" + payment_id with the secret key.
 */
app.post('/api/razorpay/verify-payment', (req: Request, res: Response) => {
  try {
    const { keySecret } = getRazorpayCredentials();

    if (!keySecret) {
      res.status(503).json({
        success: false,
        error: 'Razorpay Secret is not configured on the server. Verification unavailable.',
      });
      return;
    }

    const { razorpay_order_id, razorpay_payment_id, razorpay_signature } = req.body;

    if (!razorpay_order_id || !razorpay_payment_id || !razorpay_signature) {
      res.status(400).json({
        success: false,
        error: 'Missing order_id, payment_id, or signature in request body.',
      });
      return;
    }

    // Expected signature: HMAC SHA-256 of order_id + "|" + payment_id
    const generatedSignature = crypto
      .createHmac('sha256', keySecret)
      .update(`${razorpay_order_id}|${razorpay_payment_id}`)
      .digest('hex');

    // Constant-time comparison to prevent timing attacks
    const sigBuffer = Buffer.from(razorpay_signature);
    const expectedBuffer = Buffer.from(generatedSignature);

    if (sigBuffer.length !== expectedBuffer.length || !crypto.timingSafeEqual(sigBuffer, expectedBuffer)) {
      res.status(400).json({
        success: false,
        verified: false,
        error: 'Invalid payment signature. Verification failed.',
      });
      return;
    }

    res.json({
      success: true,
      verified: true,
      message: 'Razorpay Test payment signature verified successfully.',
      paymentId: razorpay_payment_id,
      orderId: razorpay_order_id,
    });
  } catch (error: unknown) {
    const message = error instanceof Error ? error.message : 'Error verifying payment';
    res.status(500).json({ success: false, error: message });
  }
});

// Setup Vite middleware in dev or static files in production
async function startServer() {
  const isProduction = process.env.NODE_ENV === 'production';

  if (!isProduction) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.resolve(__dirname, 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req: Request, res: Response) => {
      res.sendFile(path.resolve(distPath, 'index.html'));
    });
  }

  app.listen(PORT, () => {
    console.log(`MakeHabit server running on http://localhost:${PORT}`);
  });
}

// Only start when invoked directly
if (process.env.NODE_ENV !== 'test') {
  startServer();
}

export default app;
